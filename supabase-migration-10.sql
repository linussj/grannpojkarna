-- Grannpojkarna: läskvitton, namngivna sparmål och explicit Data API-åtkomst.
-- Kör efter supabase-migration-9.sql.

alter table public.job_messages
  add column if not exists read_at timestamptz;

alter table public.direct_messages
  add column if not exists read_at timestamptz;

create index if not exists job_messages_unread_idx
  on public.job_messages (job_id, created_at desc)
  where read_at is null;

create index if not exists direct_messages_unread_idx
  on public.direct_messages (recipient_id, created_at desc)
  where read_at is null;

drop policy if exists "Job participants can mark received messages read" on public.job_messages;
create policy "Job participants can mark received messages read"
on public.job_messages for update
to authenticated
using (
  sender_id <> (select auth.uid())
  and exists (
    select 1
    from public.jobs
    where jobs.id = job_messages.job_id
      and (
        jobs.user_id = (select auth.uid())
        or jobs.performer_id = (select auth.uid())
      )
      and jobs.status in ('accepted', 'in_progress', 'completed')
  )
)
with check (
  sender_id <> (select auth.uid())
  and read_at is not null
  and exists (
    select 1
    from public.jobs
    where jobs.id = job_messages.job_id
      and (
        jobs.user_id = (select auth.uid())
        or jobs.performer_id = (select auth.uid())
      )
      and jobs.status in ('accepted', 'in_progress', 'completed')
  )
);

drop policy if exists "Recipients can mark direct messages read" on public.direct_messages;
create policy "Recipients can mark direct messages read"
on public.direct_messages for update
to authenticated
using (recipient_id = (select auth.uid()))
with check (
  recipient_id = (select auth.uid())
  and read_at is not null
);

grant select, insert on public.job_messages to authenticated;
grant update (read_at) on public.job_messages to authenticated;
grant select on public.direct_messages to authenticated;
grant update (read_at) on public.direct_messages to authenticated;

create table if not exists public.savings_goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 2 and 80),
  target_amount_sek integer not null check (target_amount_sek between 1 and 100000000),
  saved_amount_sek integer not null default 0 check (saved_amount_sek between 0 and 100000000),
  target_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists savings_goals_user_created_idx
  on public.savings_goals (user_id, created_at desc);

alter table public.savings_goals enable row level security;

drop policy if exists "Users can read own savings goals" on public.savings_goals;
create policy "Users can read own savings goals"
on public.savings_goals for select
to authenticated
using (user_id = (select auth.uid()));

drop policy if exists "Users can create own savings goals" on public.savings_goals;
create policy "Users can create own savings goals"
on public.savings_goals for insert
to authenticated
with check (user_id = (select auth.uid()));

drop policy if exists "Users can update own savings goals" on public.savings_goals;
create policy "Users can update own savings goals"
on public.savings_goals for update
to authenticated
using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));

drop policy if exists "Users can delete own savings goals" on public.savings_goals;
create policy "Users can delete own savings goals"
on public.savings_goals for delete
to authenticated
using (user_id = (select auth.uid()));

revoke all on public.savings_goals from anon, authenticated;
grant select, insert, update, delete on public.savings_goals to authenticated;
grant usage, select on sequence public.savings_goals_id_seq to authenticated;

drop trigger if exists savings_goals_set_updated_at on public.savings_goals;
create trigger savings_goals_set_updated_at
before update on public.savings_goals
for each row execute function public.set_updated_at();

-- Behåll ett eventuellt tidigare ensamt sparmål som ett namngivet mål.
insert into public.savings_goals (user_id, name, target_amount_sek)
select p.id, 'Mitt sparmål', p.savings_goal_sek
from public.profiles p
where p.savings_goal_sek is not null
  and not exists (
    select 1 from public.savings_goals sg where sg.user_id = p.id
  );
