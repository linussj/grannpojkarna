create or replace function public.get_job_applications(p_job_id bigint)
returns table (
  application_id bigint,
  performer_id uuid,
  message text,
  proposed_price_sek integer,
  status text,
  created_at timestamptz,
  display_name text,
  bio text,
  service_area text,
  skills text[],
  avatar_path text,
  average_rating numeric,
  review_count bigint
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.jobs
    where id = p_job_id and user_id = auth.uid()
  ) then
    return;
  end if;

  return query
  select
    ja.id,
    ja.performer_id,
    ja.message,
    ja.proposed_price_sek,
    ja.status,
    ja.created_at,
    p.display_name,
    p.bio,
    p.service_area,
    p.skills,
    p.avatar_path,
    coalesce(round(avg(r.rating)::numeric, 2), 0),
    count(r.id)
  from public.job_applications ja
  join public.profiles p on p.id = ja.performer_id
  left join public.reviews r on r.reviewee_id = ja.performer_id
  where ja.job_id = p_job_id
  group by ja.id, p.id
  order by
    case ja.status when 'accepted' then 0 when 'pending' then 1 else 2 end,
    ja.created_at asc;
end;
$$;

create or replace function public.accept_job_application(
  p_application_id bigint,
  p_agreed_price_sek integer
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_job_id bigint;
  v_performer_id uuid;
begin
  if p_agreed_price_sek is null or p_agreed_price_sek < 1 or p_agreed_price_sek > 10000000 then
    raise exception 'Invalid agreed price';
  end if;

  select ja.job_id, ja.performer_id
  into v_job_id, v_performer_id
  from public.job_applications ja
  join public.jobs j on j.id = ja.job_id
  where ja.id = p_application_id
    and ja.status = 'pending'
    and j.status = 'open'
    and j.user_id = auth.uid();

  if v_job_id is null then
    raise exception 'Application not available';
  end if;

  update public.job_applications
  set status = case when id = p_application_id then 'accepted' else 'declined' end
  where job_id = v_job_id and status = 'pending';

  update public.jobs
  set status = 'matched', performer_id = v_performer_id, agreed_price_sek = p_agreed_price_sek
  where id = v_job_id and user_id = auth.uid();

  return true;
end;
$$;

create or replace function public.complete_job(p_job_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.jobs
  set status = 'completed', completed_at = now()
  where id = p_job_id
    and user_id = auth.uid()
    and performer_id is not null
    and status = 'matched';

  if not found then
    raise exception 'Job cannot be completed';
  end if;

  return true;
end;
$$;

revoke all on function public.get_job_applications(bigint) from public;
revoke all on function public.accept_job_application(bigint, integer) from public;
revoke all on function public.complete_job(bigint) from public;

grant execute on function public.get_job_applications(bigint) to authenticated;
grant execute on function public.accept_job_application(bigint, integer) to authenticated;
grant execute on function public.complete_job(bigint) to authenticated;
