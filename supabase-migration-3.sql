alter table public.profiles
  add column if not exists avatar_path text,
  add column if not exists savings_goal_sek integer;

alter table public.profiles drop constraint if exists profiles_savings_goal_check;
alter table public.profiles
  add constraint profiles_savings_goal_check
  check (savings_goal_sek is null or savings_goal_sek between 1 and 100000000);

alter table public.jobs
  add column if not exists performer_id uuid references auth.users(id) on delete set null,
  add column if not exists agreed_price_sek integer,
  add column if not exists completed_at timestamptz;

alter table public.jobs drop constraint if exists jobs_agreed_price_check;
alter table public.jobs
  add constraint jobs_agreed_price_check
  check (agreed_price_sek is null or agreed_price_sek between 1 and 10000000);

create index if not exists jobs_performer_status_idx
  on public.jobs (performer_id, status, completed_at desc);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  job_id bigint not null unique references public.jobs(id) on delete cascade,
  reviewer_id uuid not null references auth.users(id) on delete cascade,
  reviewee_id uuid not null references auth.users(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  comment text check (comment is null or char_length(comment) between 2 and 600),
  created_at timestamptz not null default now()
);

create index if not exists reviews_reviewee_id_idx
  on public.reviews (reviewee_id, created_at desc);

alter table public.reviews enable row level security;

drop policy if exists "Users can read relevant reviews" on public.reviews;
create policy "Users can read relevant reviews"
on public.reviews for select
to authenticated
using (
  reviewer_id = (select auth.uid())
  or reviewee_id = (select auth.uid())
);

drop policy if exists "Job owners can review performers" on public.reviews;
create policy "Job owners can review performers"
on public.reviews for insert
to authenticated
with check (
  reviewer_id = (select auth.uid())
  and reviewer_id <> reviewee_id
  and exists (
    select 1
    from public.jobs
    where jobs.id = job_id
      and jobs.user_id = (select auth.uid())
      and jobs.performer_id = reviewee_id
      and jobs.status = 'completed'
  )
);

drop policy if exists "Performers can read assigned jobs" on public.jobs;
create policy "Performers can read assigned jobs"
on public.jobs for select
to authenticated
using ((select auth.uid()) = performer_id);

grant select, insert on public.reviews to authenticated;
grant usage, select on sequence public.reviews_id_seq to authenticated;

