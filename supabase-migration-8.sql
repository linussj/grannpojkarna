create or replace function public.notify_new_direct_message()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_sender_name text;
begin
  select coalesce(p.display_name, 'En användare')
  into v_sender_name
  from public.profiles p
  where p.id = new.sender_id;

  insert into public.notifications (user_id, type, title, body, related_user_id)
  values (
    new.recipient_id,
    'direct_message',
    'Nytt direktmeddelande',
    coalesce(v_sender_name, 'En användare') || ' har skickat ett meddelande till dig.',
    new.sender_id
  );

  return new;
end;
$$;

drop trigger if exists direct_messages_notify_insert on public.direct_messages;
create trigger direct_messages_notify_insert
after insert on public.direct_messages
for each row execute function public.notify_new_direct_message();

-- Ett timpris är inte ett slutbelopp. Därför skapas ingen utbetalningsnotis
-- för timjobb innan registrerade timmar finns i en senare betalningsversion.
create or replace function public.notify_job_status_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor_id uuid := auth.uid();
  v_amount integer;
begin
  if old.status is not distinct from new.status then
    return new;
  end if;

  if new.status = 'in_progress' then
    if new.user_id is distinct from v_actor_id then
      insert into public.notifications (user_id, type, title, body, job_id)
      values (new.user_id, 'job_started', 'Jobbet har startat', '"' || coalesce(new.title, 'Jobbet') || '" är nu markerat som pågående.', new.id);
    end if;
    if new.performer_id is not null and new.performer_id is distinct from v_actor_id then
      insert into public.notifications (user_id, type, title, body, job_id)
      values (new.performer_id, 'job_started', 'Jobbet har startat', '"' || coalesce(new.title, 'Jobbet') || '" är nu markerat som pågående.', new.id);
    end if;
  elsif new.status = 'completed' and new.performer_id is not null then
    insert into public.notifications (user_id, type, title, body, job_id)
    values (
      new.performer_id,
      'job_completed',
      'Jobbet är slutfört',
      'Beställaren har bekräftat att "' || coalesce(new.title, 'jobbet') || '" är klart.',
      new.id
    );

    if new.price_type <> 'hourly' then
      v_amount := coalesce(new.agreed_price_sek, new.budget_sek, 0);
      insert into public.notifications (user_id, type, title, body, job_id)
      values (
        new.performer_id,
        'payout_ready',
        'Ersättning klar för utbetalning',
        v_amount::text || ' kr för "' || coalesce(new.title, 'jobbet') || '" är markerat som klart för utbetalning.',
        new.id
      );
    end if;
  end if;

  return new;
end;
$$;
