-- Grannpojkarna: frivilliga mejlnotiser om nya jobb.
-- Kör efter supabase-migration-8.sql.

alter table public.profiles
  add column if not exists email_job_alert_mode text not null default 'off';

alter table public.profiles
  drop constraint if exists profiles_email_job_alert_mode_check;

alter table public.profiles
  add constraint profiles_email_job_alert_mode_check
  check (email_job_alert_mode in ('off', 'matching', 'all'));

create table if not exists public.job_email_deliveries (
  id bigint generated by default as identity primary key,
  job_id bigint not null references public.jobs(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'queued' check (status in ('queued', 'sent', 'failed')),
  provider_id text,
  error text check (error is null or char_length(error) <= 500),
  attempted_at timestamptz,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  unique (job_id, user_id)
);

create index if not exists job_email_deliveries_user_created_idx
  on public.job_email_deliveries (user_id, created_at desc);

alter table public.job_email_deliveries enable row level security;

-- Leveransloggen är endast tillgänglig för serverfunktionen med en hemlig nyckel.
revoke all on public.job_email_deliveries from anon, authenticated;
revoke all on sequence public.job_email_deliveries_id_seq from anon, authenticated;

-- Triggerfunktioner ska inte kunna anropas som publika RPC-endpoints.
revoke execute on function public.notify_matching_performers() from public, anon, authenticated;
revoke execute on function public.notify_new_job_application() from public, anon, authenticated;
revoke execute on function public.notify_application_accepted() from public, anon, authenticated;
revoke execute on function public.notify_job_status_change() from public, anon, authenticated;
revoke execute on function public.notify_new_job_message() from public, anon, authenticated;
revoke execute on function public.notify_new_direct_message() from public, anon, authenticated;

